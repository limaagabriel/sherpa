#!/usr/bin/env bash
# Usage: test-ensure-board.sh
# Input:  none; builds fixtures in a temp SHERPA_CONFIG_DIR and HOME. Needs yq and git.
# Output: "PASS: all init cases" or FAIL lines plus "FAILED".
# Exit:   0 when every case passes, 1 otherwise.
set -u
here=$(cd "$(dirname "$0")" && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
fail=0
source "$here/../lib/assert.sh"
export SHERPA_CONFIG_DIR="$tmp/cfg" HOME="$tmp/home"
export GIT_AUTHOR_NAME=t GIT_AUTHOR_EMAIL=t@t GIT_COMMITTER_NAME=t GIT_COMMITTER_EMAIL=t@t
mkdir -p "$HOME" "$tmp/elsewhere"
inv="$SHERPA_CONFIG_DIR/inventory"
repository="$tmp/repo"
git init -q "$repository"; mkdir "$repository/.sherpa"; echo "name: p" >"$repository/.sherpa/project.yaml"
git -C "$repository" add -A; git -C "$repository" commit -qm init

run() { out=$(cd "${cwd:-$repository}" && bash "$here/ensure-board.sh" "$@" 2>"$tmp/err"); rc=$?; err=$(cat "$tmp/err"); }

# no args in a repo with a project-local pack
run; assert_exit "init exit" "$rc" 0; assert_eq "init stdout" "$out" "$inv/p"
for s in backlog frame shape implement analyze done; do
  [ -d "$inv/p/$s" ] || { echo "FAIL [stage]: missing $s"; fail=1; }
done
assert_contains "board built" "$(cat "$inv/p/board.md" 2>&1)" "generated by sherpa"
conf="$inv/p/settings.yaml"
assert_eq "settings repository" "$(yq .repository "$conf")" "$repository"
assert_eq "settings path" "$(yq .worktree.path "$conf")" "$tmp/p-worktrees/\$TICKET_ID"
assert_eq "no create by default" "$(yq '.worktree.create // "none"' "$conf")" "none"
assert_eq "init stderr" "$err" ""

# the runner: add-dir, quoted task, an allow-list, never a bypass
runner=$(yq .runner "$conf")
assert_contains "runner add-dir" "$runner" '--add-dir "$(dirname "$TICKET_FILE")"'
assert_contains "runner mode" "$runner" "--permission-mode acceptEdits"
assert_contains "runner allow-list" "$runner" "--allowedTools"
assert_not_contains "runner bypass" "$runner" "dangerously"
assert_not_contains "runner broad git" "$runner" "Bash(git *)"
assert_not_contains "runner push" "$runner" "git push"
assert_contains "runner git commit" "$runner" "Bash(git commit:*)"
# it survives bash -c with a path holding spaces: the prompt comes first, one argument each
mkdir -p "$tmp/bin"; printf '#!/bin/sh\nfor a; do echo "[$a]"; done >"$FAKE_OUT"\n' >"$tmp/bin/claude"
chmod +x "$tmp/bin/claude"
task="$tmp/a dir/T-1.md"
FAKE_OUT="$tmp/argv" PATH="$tmp/bin:$PATH" TICKET_STAGE=shape TICKET_FILE=$task bash -c "$runner"
assert_eq "runner argv" "$(sed -n '1,4p' "$tmp/argv" | tr '\n' ' ')" \
  "[-p] [/sherpa:shape --unattended \"$task\"] [--permission-mode] [acceptEdits] "
assert_contains "runner add-dir value" "$(cat "$tmp/argv")" "[$tmp/a dir]"

# ensure-worktree.sh accepts the file as written (default create makes a worktree)
wt=$(bash "$here/ensure-worktree.sh" p T-1 2>"$tmp/err"); assert_exit "worktree exit" $? 0
assert_eq "worktree path" "$wt" "$tmp/p-worktrees/T-1"
assert_eq "worktree branch" "$(git -C "$wt" branch --show-current)" "T-1"

# a second run leaves an edited settings.yaml byte-identical
echo "# my edit" >>"$conf"; cp "$conf" "$tmp/edited"
run; assert_exit "rerun exit" "$rc" 0; assert_eq "rerun stdout" "$out" "$inv/p"
cmp -s "$conf" "$tmp/edited" || { echo "FAIL [rerun]: settings.yaml changed"; fail=1; }

# an explicit pack and --repository override the detection, from outside any repo
cwd="$tmp/elsewhere" run q --repository "$repository"
assert_exit "override exit" "$rc" 0; assert_eq "override stdout" "$out" "$inv/q"
assert_eq "override repository" "$(yq .repository "$inv/q/settings.yaml")" "$repository"
# a path with a single quote survives the YAML quoting
qr="$tmp/o'b"; git init -q "$qr"; mkdir "$qr/.sherpa"; echo "name: qp" >"$qr/.sherpa/project.yaml"
git -C "$qr" add -A; git -C "$qr" commit -qm init
cwd="$tmp/elsewhere" run qp --repository "$qr"; assert_exit "quote exit" "$rc" 0
assert_eq "quote repository" "$(yq .repository "$inv/qp/settings.yaml")" "$qr"
assert_eq "quote path" "$(yq .worktree.path "$inv/qp/settings.yaml")" "$tmp/qp-worktrees/\$TICKET_ID"
# a settings.yaml that is a symlink is left alone
rm -f "$inv/qp/settings.yaml"; ln -s "$tmp/edited" "$inv/qp/settings.yaml"
cwd="$tmp/elsewhere" run qp --repository "$qr"; assert_exit "symlink exit" "$rc" 0
cmp -s "$tmp/edited" "$inv/qp/settings.yaml" && [ -L "$inv/qp/settings.yaml" ] || { echo "FAIL [symlink]: replaced"; fail=1; }
# a linked worktree still records the main worktree
cwd="$wt" run r; assert_eq "linked repository" "$(yq .repository "$inv/r/settings.yaml")" "$repository"
# --repository alone takes the pack from that repo
cwd="$tmp/elsewhere" run --repository "$repository"; assert_eq "repository-only stdout" "$out" "$inv/p"

# a workspace pack whose detect misses the default worktree path draws a warning, not a failure
mkdir -p "$tmp/ws/w"; printf 'name: w\ndetect: case "$CWD" in %s) ;; *) false ;; esac\n' "$tmp/plain" >"$tmp/ws/w/project.yaml"
mkdir -p "$SHERPA_CONFIG_DIR/projects"; cp -r "$tmp/ws/w" "$SHERPA_CONFIG_DIR/projects/w"
git init -q "$tmp/plain"
cwd="$tmp/plain" run w --repository "$tmp/plain"; assert_exit "ws exit" "$rc" 0
assert_contains "ws no detect match" "$err" "detect does not match"
rm -f "$inv/w/settings.yaml"; sed -i "s|^detect:.*|detect: true|" "$SHERPA_CONFIG_DIR/projects/w/project.yaml"
cwd="$tmp/plain" run w --repository "$tmp/plain"; assert_eq "ws match quiet" "$err" ""
rm -rf "$SHERPA_CONFIG_DIR/projects"

# failures
cwd="$tmp/elsewhere" run; assert_exit "not a repo exit" "$rc" 1; assert_contains "not a repo msg" "$err" "not a git repo"
cwd="$tmp/plain" run; assert_exit "no pack exit" "$rc" 1; assert_contains "no pack msg" "$err" "no pack found"
for bad in .hidden a/b "a b"; do
  run "$bad"; assert_exit "bad name $bad" "$rc" 1; assert_contains "bad name msg $bad" "$err" "invalid pack name"
done
run '' ; assert_exit "empty name" "$rc" 1
[ ! -e "$inv/.hidden" ] || { echo "FAIL [bad name]: created $inv/.hidden"; fail=1; }
run --bogus; assert_exit "unknown flag" "$rc" 2
run a b; assert_exit "two packs" "$rc" 2
run --repository; assert_exit "--repository without value" "$rc" 2

[ "$fail" -eq 0 ] && echo "PASS: all init cases" || { echo FAILED; exit 1; }
